-- ============================================================================
-- V65：演示租户资源池留出可分配余量（修复「机构配额分配必失败」）
-- ============================================================================
--
-- 现象：租户端「机构管理 → 配额」保存必失败，提示「分配超额…（FR-C2）」。
--
-- 根因（实测数据库，非推测）：
--   租户 2（大数据管理局）池总量 5,000,000，V24 已给 3 家机构分配 4,700,000 → 可分配仅 300,000；
--   租户 3（卫生健康局）  池总量   800,000，已分配 600,000               → 可分配仅 200,000。
--   即演示数据一上线就把 94% / 75% 的池子占满。而 FR-C2 门禁
--   （Σ机构配额 ≤ 资源池总量）本身是正确的 —— 于是「按设计正确拒绝」被读成「功能坏了」。
--
-- 处理：只抬升演示租户（2 / 3）的池总量，留出真实的演练余量。
--   * 不含任何业务逻辑改动：门禁照旧，超额仍会被拒；
--   * 只写 tenant_resource_pool 一列，不动 org_quota / dept_quota 与历史流水；
--   * 用 GREATEST 保证幂等：已被人为调大过的池子不会被这次迁移调小。
--
-- 配套（同一口径的第二处）：scripts/reset_v24_demo.py 的资源池复位语句同步到本值，
-- 否则「复位脚本把池子调回 5,000,000 ⇒ 分配又必失败」，缺陷会被复位动作带回。
-- ============================================================================

UPDATE `tenant_resource_pool`
SET `token_total` = GREATEST(`token_total`, 20000000)
WHERE `tenant_id` = 2;

UPDATE `tenant_resource_pool`
SET `token_total` = GREATEST(`token_total`, 3000000)
WHERE `tenant_id` = 3;
