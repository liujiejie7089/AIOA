-- V88 专家目录 2.0：会话级「专家化」+ 13 位真正能干活的领域专家
--
-- ## 为什么要动这一版
--
-- 用户端的「专家」此前只是**目录卡片**：选了某位专家，会话里模型拿到的仍是通用助手提示词。
-- 链条断在最后一跳 —— 后端 `resolveExpertSettings` 只在会话绑了**数字员工**时才跑，
-- 而专家会话恰恰**不绑数字员工**；即使跑到了，`expert_settings.systemPrompt`
-- 也从未被 agent 的 `build_messages` 消费（agent 侧只读 temperature/topK/threshold/…）。
-- 结果：13 位专家回答同质化，用户问「法律专家」得到的仍是通用助手口径。
--
-- ## 本迁移做三件事
--
-- 1) `chat_conversation.expert_key`：把「这个会话是哪位专家」**落库**。
--    不能让前端每次 run 临时带参决定 —— 刷新/续跑/多轮都会丢，且历史会话无法复现人设。
--
-- 2) 补齐专家目录（`ai_expert`，tenant_id=0 全局模板）：13 位领域专家。
--    复用既有 expert_key（policy/legal/labor/contract/ip/compliance/tax/data_analyst/startup），
--    新增 doc_writer / meeting_minutes / translator / procurement 四位。
--    **不重建已存在的行**（管理员可能改过名称/简介/排序）—— 只补缺行、只拉回 enabled。
--
-- 3) 写 `expert_config` GLOBAL 层片段：`systemPrompt` / `knowledgeScope` / 采样参数。
--    这是「专家真的有专业能力」的唯一来源（agent 侧从 `expert_settings.systemPrompt` 取）。
--    幂等口径：`JSON_MERGE_PATCH(我们的片段, 既有 config_json)` —— 既有键**优先**，
--    只为缺失的键补值。管理员在「专家配置」页填过的提示词绝不会被迁移覆盖。
--
-- ## 为什么专家行要复制给「已有自建目录」的租户
--
-- `CatalogService.experts` 的口径是「本租户可用专家为空 ⇒ 回落全局模板」，**本租户非空则不回落**。
-- 演示租户（WJJ-DEMO / DSJ-DEMO）各自已有自建专家行，光加 tenant_id=0 的行它们看不到；
-- 故按 V62 同一范式：只给**已经存在自建行**的租户补缺的 key，不碰它们的既有行。
-- 全新租户没有自建行 ⇒ 天然回落全局目录，无需播种。

