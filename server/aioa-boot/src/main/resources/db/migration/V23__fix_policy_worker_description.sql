-- ============================================================================
-- V23: 修正「政策快讯员」简介（走查发现 D-1 数据侧延伸）
--
-- 背景：V22 已把该员工的任务内容（task_prompt）具体化，但「简介」（description）
--       仍是笼统的「重新汇总这项工作」。该字段会进入会话的身份设定，
--       导致数字员工在被问到职责时只能复述「只负责重新汇总这项工作」，
--       既说不清自身范围，也让员工卡片文案没有信息量。
-- 做法：仅将该员工的简介改写为可读的职责描述；不改动其他员工。
-- ============================================================================

UPDATE `agent_worker`
SET `description` = '每日汇总近 7 天行业政策动态，按「政策名称 / 发布主体 / 核心要点 / 影响对象 / 建议动作」输出要点'
WHERE `deleted_at` IS NULL
  AND `name` = '政策快讯员'
  AND (`description` IS NULL OR `description` IN ('重新汇总这项工作', '重新汇总这项工作。'));
