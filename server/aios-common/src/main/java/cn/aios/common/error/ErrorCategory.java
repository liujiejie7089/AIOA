package cn.aios.common.error;

/**
 * 错误分类：前端/网关/监控可按分类做不同处置（重试、跳登录、提示联系管理员），
 * 不必去枚举具体码。分类是**稳定契约**，具体码允许增加。
 */
public enum ErrorCategory {

    /** 参数/表单不合法：用户自己能改，改完重试即可。 */
    VALIDATION,
    /** 未登录 / 令牌过期 / 凭证无效：应引导去登录。 */
    AUTHENTICATION,
    /** 已登录但无权限：换账号或找管理员授权。 */
    PERMISSION,
    /** 资源不存在（含路径不存在）：检查地址或数据是否已被删除。 */
    NOT_FOUND,
    /** 状态冲突（重复提交、已被占用、并发改动）：刷新后重试。 */
    CONFLICT,
    /** 触发限流/配额：等一会儿或提额。 */
    RATE_LIMIT,
    /** 外部依赖（模型/连接器/第三方）失败：多为瞬时，可重试。 */
    UPSTREAM,
    /** 服务内部错误：用户无需理解细节，凭错误编号找运维。 */
    INTERNAL
}
