"""数字员工回答结构契约（需求项 6「数字员工标准流程」的最后一段）。

职责边界有两种落法，缺一不可：

  1. **事前**：职责限定写进系统提示，让模型不去答边界外的问题
     （见 ``agent_runtime._build_messages`` 的 scope 分支）。
  2. **事后**：回答**答不了时**要交代清楚。只写「不要越界」是不够的 ——
     用户真正卡住的场景是「AI 说不行，但没说找谁办、也没说下一步做什么」。

故本模块定义回答结构，并提供两个能力：

  * :func:`rules` —— 生成注入系统提示的**行为**规则（只影响生成，是软约束）。
    **当前口径（2026-10-15 起，用户指定）＝严格知识库口径**：只依据本轮提供的四类资料作答、
    逐维度覆盖不跳项、缺失项标注到具体维度、统计/对比类用表格、输出前强制自检 —— 详见函数说明。
  * :func:`audit` —— 对已生成回答做**六段式**结构自检（历史遗留，是硬判定），返回缺失了哪几段。
    自检结果由调用方决定怎么用，**不在此处改写模型原文** —— 事后改写真假难辨，
    也破坏了「回答即原文」的可审计性。

    ⚠️ 自 2026-10-12 起，六段**不再是每次回答的必给模板**（见 :func:`rules` 的历史说明），
    因此 ``audit`` 报出的「缺失」只应作**可选的结构化体检**，**不再代表回答不合格**；
    不要把它的 ``missing`` 当成质量扣分项去提示用户。
    ⚠️ 同理，2026-10-15 的新口径**也不是六段**（它管的是来源/覆盖/表格/标注/自检，与六段无关）
    ⇒ ``audit`` 与 ``rules`` 现在**不是同一套标准**，不要把 ``audit`` 的结果当作新口径的验收。

六段结构的来源是需求项 6 的链路：
前置检查 → 权限申请 → 审批授权 → 创建向导 → 表单配置 → 运行计费审计回收。
对应到一次回答就是：先给结论，再说清当前状态与卡点，然后划边界、给唯一下一步、
给出可转述给管理员的话术，最后说明放行后会自动接上什么。
**但它只在该链路真的被触发时才成立**（即「用户提问涉及权限」的场景），
不是任何提问都该套的外壳；新口径里仅保留「权限话题补下一步 + 可转述话术」这一条
（见 :func:`rules` 规则 10）。

"""
from __future__ import annotations

import re

# 六段结构：key、中文名、以及「这一段的写作要求」。
SECTIONS: list[tuple[str, str, str]] = [
    ("conclusion", "结论先行",
     "第一句直接给结论：能做 / 不能做 / 需要先补什么。不要用铺垫开头。"),
    ("status", "状态卡",
     "用 2-4 行短句列清当前事实（已具备什么、缺什么、卡在哪一项），每行一个事实，可被逐条核对。"),
    ("boundary", "能力边界",
     "明确说明你这条职责能覆盖到哪、覆盖不到哪；覆盖不到的部分指出应由谁承担。"),
    ("next_step", "唯一下一步",
     "只给一个动作（最多再补一个备选），写清操作路径。多条并列会把选择成本推回用户。"),
    ("admin_script", "管理员话术",
     "若需他人放行，给出一段可直接转述给管理员的话，含具体权限码/资源名与办理路径。"),
    ("after_approval", "通过后续接",
     "说明对方放行后会自动发生什么（谁受理、多长时间、结果推到哪里），让用户知道不用再追问。"),
]

SECTION_KEYS: list[str] = [k for k, _, _ in SECTIONS]

# 自检用的弱标记：命中任一即认为该段存在。
# 刻意保持「弱」——结构自检是为了提示，不是为了扣分，误报比漏报更伤可用性。
_MARKERS: dict[str, list[str]] = {
    "conclusion": [r"^[^。\n]{0,60}[。！\n]", r"结论", r"建议", r"不能", r"可以", r"需要先"],
    "status": [r"当前状态", r"状态：", r"^[-·•\d]", r"已具备", r"缺少", r"卡在"],
    "boundary": [r"职责", r"范围", r"边界", r"只能", r"不负责", r"不处理"],
    "next_step": [r"下一步", r"你(可以|需要|要)", r"请(先|在|点|到)", r"建议你"],
    "admin_script": [r"管理员", r"可转述", r"联系.*(开通|授权)", r"申请"],
    "after_approval": [r"通过后", r"审批通过", r"放行后", r"生效后", r"之后会"],
}


def rules(scope: dict | None = None) -> list[str]:
    """回答**行为**规则 → 系统提示行。

    三次变更（全部用户反馈驱动，历史别丢）：

    * 2026-10-12 ①：原实现要求**每次回答都按六段**（结论先行/状态卡/能力边界/唯一下一步/
      管理员话术/通过后续接）组织且禁止省略任一段 ⇒ 实测代价是「答非所问的冗长」：上传一个
      文件问「这里面有什么」也被撑成六段（用户原话：**回答太多，只需要回答用户提问相关的**）。
      故六段降级为「可选清单」（``SECTIONS`` 仅供 :func:`card` 与人工查看）。
    * 2026-10-12 ②：「做不了就补下一步」收窄为**只限权限话题**（用户明确要求）。
    * **2026-10-15 ③（本次）**：用户给出新口径 —— **严格基于知识库/已提供资料、全维度覆盖、
      结构化（统计与对比类用表格）、缺失项逐维度标注、输出前强制自检**。本次把风格规则改写为
      这一套，**不再**用「能一句答清就一句」当总纲。

    ⚠️ 与②的冲突已在本函数内消解，勿再退回：新口径的「覆盖」是**覆盖用户问到的维度**，
    不是「每题都展开」；故规则 8 显式禁止为用户没问到的维度凑段落、并把篇幅还给问题本身。
    这两条必须同时在场 —— 只留「必备齐」会回到 2026-10-12 ① 的冗长，只留「只答所问」则
    满足不了本次「逐维度交代、不得跳项」的要求。

    ⚠️ 「只依据资料作答」的**范围**是本机制特有的适配（勿照抄成「只依据知识库」）：数字员工
    还能从**工具返回**（额度/审批/待办）与**对话内参考文档**读取事实；写成「只依据知识库」会让
    它把有工具事实支撑的问题也回「知识库暂未收录」，是回归。故规则 1 明确四类来源。

    ``scope`` 非空（会话绑定了数字员工）时只多加一条「越界一句话拒答」，同样不要求展开。
    """
    lines = [
        "【作答姿态 · 必须严格遵守】回答必须**严格基于本轮实际提供的资料**，全维度覆盖、"
        "结构化呈现、不臆测、不含糊。你是依据内部知识库与业务数据作答的精准问答助手。",
        "【事实来源白名单】",
        # ⚠️ 本段**刻意不写出**那两个注入块的定界符原文（如「【参考文档】」「【知识库参考】」）：
        # 它们被 agent_runtime 用作「块是否真的被注入」的判据（test_attachment_docs.py 与
        # _check_kb_toggle.py 都在断言「无附件/关知识库时该定界符不得出现」）。一旦在提示词里
        # 引用其字面量，这些哨兵会**恒为真**（永远能 grep 到）⇒ 判据失效。用自然语言指代即可。
        "1. 你只能依据本轮真实提供给你的四类资料作答：① 知识库召回内容；"
        "② 工具调用的返回结果；③ 对话内上传的参考文档；④ 你的职责定义。"
        "**不得编造、不得推演、不得引用上述范围之外的外部知识**；资料里没有的数字、名称、"
        "时间、条款、人名，一个都不要写出来。",
        "【作答步骤】",
        "2. 先把用户问题拆成**应答清单**：列出他问到的每一个查询点、每一个统计维度、每一个子问题。"
        "（这一步在内部完成，**不要把清单本身输出给用户**。）",
        "3. 对照资料**逐项填答**：清单里的每一项都必须有交代，**不得跳过任何一项**，"
        "也不得只挑有数据的那几项来答。**信息不全或缺少检索关键词时，先按现有资料把能答的"
        "答完、把缺的维度标注清楚，不要只用一句反问代替回答**（反问只能作为补充，"
        "且必须放在已给结论之后）—— 只回一句「请提供关键词」等于没回答，是明确不允许的。",
        "【缺失项怎么写 · 必须落到具体维度】",
        "4. 资料里确实没有对应内容的项，写「知识库暂未收录」，并**点名是哪一个维度**；"
        "若判断该维度理应有资料、只是本轮没检索到，写「当前检索未返回相关内容」。"
        "**禁止**用「未提供详细数据」「相关资料不足」「暂无更多信息」这类笼统说法代替 —— "
        "必须明确到具体维度，不得删掉该维度。",
        "【结构化输出】",
        "5. 统计类、多维度对比类内容**必须用表格呈现**，不要用长段文字罗列数字。"
        "统计类表格固定三列：`维度层级 | 数量 | 数据来源·备注`；**用户提到的所有维度都必须出现在表里**，"
        "没有数据的维度**保留该行**并在对应列标注缺失状态，**不得删行**。"
        "（非数字的对比类同理用表格，列按内容定，但必须含一列写清来源。）",
        "6. 同一维度存在多条不同数据时，采用**最新发布、来源最权威**的那条，"
        "并在「数据来源·备注」列标明出处。",
        "【补充建议】",
        "7. 对标注了「知识库暂未收录」或「当前检索未返回相关内容」的项，可各给 1-2 条**具体的**"
        "权威获取渠道（写出机构名或系统入口，例如某主管部门官网、某公开名录），"
        "不要写「建议咨询相关部门」这类空泛表述。"
        "（这是「去哪里能查到这份数据」的**来源指引**，不是办理权限/审批的指引 —— 后者见规则 10。）",
        "【不要凑内容 · 与上文同等重要】",
        "8. **不要**为用户没问到的维度、也不要为了「显得完整」而添加段落、分节标题或固定模板；"
        "没问到就不写。篇幅随问题本身：简单的单点提问，一两句答清即可，不必套表格。",
        "【输出前自检 · 逐条核对后再发】",
        "9. 发出去之前自查下列五项，全部通过再输出：① 用户问到的每个维度是否都有交代？"
        "② 每一项是否能对应到资料、或已明确标注缺失？③ 统计/对比内容是否用了表格？"
        "④ 所有数字是否都来自资料、没有一个是编的？⑤ 缺失项是否写到了**具体维度**，"
        "而不是笼统说法？",
    ]
    lines.append(
        "10. 仅当用户提问**涉及权限**（权限不足／需要授权或审批放行／询问自己有哪些权限）时，"
        "才在上述结构之外再补两点：① 下一步的具体动作（写清操作路径）；② 若需他人放行，"
        "给一段可直接转述给对方的话（含具体权限码或资源名）。**除权限问题外，一律不要输出"
        "办理指引、联系人/管理员信息或下一步建议** —— 包括你答不了、问题超出职责、"
        "查不到数据的情况，直接说明即可；也不要在用户没提权限时主动提议"
        "「要不要帮你申请/开通权限」（把话题从用户的问题引到权限上，同样属于答非所问）。")
    if scope:
        lines.append(
            "11. 你只在上方职责范围内作答；越界的问题用一句话说明并建议改问对应入口，不必展开。")
    return lines


def card(role: str) -> dict:
    """按类型给出确定性的「能力边界卡」。

    与 :func:`rules` 不同，这里**不经模型**：边界文案来自类型元数据的固定定义，
    因此前端可以直接渲染成卡片，不依赖 LLM 是否听话。这也让「边界」在
    「创建前预览」与「会话中提示」两处口径完全一致。

    文案源与 ``worker_intake._ROLES`` 同源（后者是类型元数据的唯一出处），
    这里只负责把它整理成卡片的形状，避免第二份定义。
    """
    from aios_ai.intent.intake import _ROLES  # 局部导入：避免模块级循环

    key = (role or "").upper()
    if key not in _ROLES:
        # 与 Java 侧 WorkerRole.of 同口径：未知类型一律降级 GENERAL。
        # 只降级文案而不降级 role 字段，会出现「标签写着 X、边界却是通用助手」的自相矛盾。
        key = "GENERAL"
    meta = _ROLES[key]
    return {
        "role": key,
        "roleName": meta["roleName"],
        "boundary": meta["boundary"],
        "nextStep": meta["nextStep"],
        "formFields": list(meta.get("formFields") or []),
        "sections": [{"key": k, "name": n, "hint": h} for k, n, h in SECTIONS],
    }


def audit(answer: str) -> dict:
    """对回答做六段结构自检，返回 ``{ok, missing, sections}``。

    只做**存在性**判断，不判断质量；命中即通过，宁可漏报也不误报。
    """
    text = answer or ""
    sections = {}
    for key in SECTION_KEYS:
        sections[key] = any(re.search(p, text, re.M | re.I) for p in _MARKERS[key])
    missing = [k for k in SECTION_KEYS if not sections[k]]
    return {"ok": not missing, "missing": missing, "sections": sections}


def audit_hint(result: dict) -> str:
    """把自检结果转成一句给用户看的提示（缺失段用中文名回显）。"""
    missing = (result or {}).get("missing") or []
    if not missing:
        return ""
    names = {k: n for k, n, _ in SECTIONS}
    return "本次回答缺少结构段：" + "、".join(names.get(k, k) for k in missing) + \
        "。可直接追问「下一步我该做什么」。"
