"""agent loop 的**完成判定**（确定性，不依赖模型自觉）。

## 为什么需要它

原先 loop 的结束判定只有一条：「本轮有没有 tool_calls」——没有就 ``finalize``。
它没有回答真正该问的问题：**用户的目标达成了吗？**

2026-11-06 现场：用户说「帮我写一份周报」，代码已在 prepare 阶段把多源素材注入 system，
模型不需要再调工具，于是它输出「我先把本周的原始素材拉齐，再整理成周报。」就停了。
loop 判定「零工具调用 ⇒ 最终回答」，run 记 SUCCEEDED，界面只剩一句导语 + 一张
「数据来源 · 4 个」的引用卡 —— 周报正文一个字都没有，且系统认为这轮成功了。

提示词只能降低概率（本项目已有多次「写了 ≠ 模型会用」的实测），所以这里把
**完成判定**做成代码侧的闸：不达标就回到 agent 再跑一轮，把成稿补完。

## 为什么是「接着输出」而不是「撤回重来」

流式 delta 已经发给前端，前端没有撤回通道。因此不丢弃导语，而是让下一轮
紧接着输出完整正文 —— 用户看到的是「导语 + 成稿」，语义连贯，而不是停在导语。
``content_parts`` 累积拼接，落库 / 界面 / 上下文三者仍同源。

## 判据刻意收窄

只对**能客观判定**的中间态动手：空内容、明确的未完收尾、短句且只有计划/承诺、
交付类任务缺成稿结构。正常回答（哪怕短，如「你好」）不受影响。
"""
from __future__ import annotations

import re

# 最多补几轮。与 MAX_TOOL_ROUNDS 分开计：工具轮是「做」，补齐轮是「把话说完」。
MAX_DELIVERY_RETRIES = 2

# 交付类诉求：这些任务必须产出**成稿**，不能只给计划、素材清单或方法说明。
DELIVERY_RE = re.compile(
    r"周报|日报|月报|季报|半年报|年报|工作总结|总结|汇总|归纳|整理成|梳理|复盘|"
    r"述职|汇报材料|工作汇报|写一份|写个|起草|拟一份|报告|方案|清单|台账"
)

# 明确的「未完收尾」：命中即视为中间态，不论长短。
UNFINISHED_RE = re.compile(
    r"待续|未完待续|稍后(补充|更新|再|继续|提供|奉上)|后续(再|继续)(补|写|整理|提供|完善)|"
    r"下次再说|先写到这|先到这里|剩余(部分|内容|工作).{0,12}(自行|另|下次|由你|请您|请自行)|"
    r"其余部分.{0,10}(自行|略|不再)|(自行|请自行)(处理|补充|完善)"
)

# 只说要做什么、还没做：「我先…再…」「正在整理」「请稍等」…
# ★ 刻意不认裸的「我先」——「我先说结论：…」是**正在给内容**，不是计划句。
#   只认「我先 + 后续动作动词」或「我先…再…」这种真的把活推到后面的形态。
PLAN_ONLY_RE = re.compile(
    r"我先(去|把|来|查|检索|整理|拉取|汇总|收集|看|读|核对|确认)|"
    r"我(会|将)(去|把|再|稍后|随后|接下来|先)|"
    r"接下来(我|会|将)|马上(为你|为您)?|"
    r"正在(为你|为您)?(查询|检索|查看|整理|读取|拉取|汇总|收集)|请稍等|稍候|"
    r"先把.{0,24}再|拉齐.{0,12}再|先去.{0,12}然后"
)

# 成稿的结构特征：小节标题 / 编号条目 / 项目符号 / 交付三要素 / 周报惯用分节。
SECTION_RE = re.compile(
    r"(^|\n)\s*(#{1,4}\s|\d+[.、)]\s|[-*•]\s|[一二三四五六七八九十]+[、.]\s)|"
    r"【[^】]+】|完成状态|已覆盖|完成依据|数据来源|本周|下周|一[、.]|主要工作|进展"
)

# 交付三要素：用户原话要求最终交付**必须**包含「完成状态、已覆盖的全部需求、完成依据」。
# 旧版只要求任意一项（连「数据来源」都算），比用户要求松 ⇒ 会出现「正文成稿了但没交代
# 完成状态」仍判绿、闸不补齐。这里改为三项齐全；非交付类任务不受影响。
DELIVERY_REQUIRED = ("完成状态", "已覆盖", "完成依据")
EVIDENCE_RE = re.compile(r"完成状态|已覆盖|完成依据|数据来源|依据|来源|据[^，。]{2,8}(会话|邮件|审批|日历|知识库)")

# 交付类任务的正文长度下限：低于它基本不可能是一份周报/报告。
MIN_DELIVERY_CHARS = 140
# 「短句且只有计划」的长度上限：超过这个长度默认已有正文，避免误伤「我先说结论，再展开」。
MAX_PLAN_ONLY_CHARS = 90


def is_delivery_request(text: str | None, aggregated: bool = False) -> bool:
    """这一轮是不是「要一份成稿」的任务。聚合任务一律算（代码已代拉素材，本就该成文）。"""
    if aggregated:
        return True
    return bool(DELIVERY_RE.search(text or ""))


def assess_delivery(content: str | None, delivery: bool) -> tuple[bool, str]:
    """判断这段正文能否作为**最终交付**。

    :return: ``(是否达标, 未达标原因)``；原因会写进补齐指令与日志，便于排查。
    """
    t = (content or "").strip()
    if not t:
        return False, "本轮没有正文"
    if UNFINISHED_RE.search(t):
        return False, "命中「待续 / 稍后补充 / 剩余部分自行处理」类未完收尾"
    if len(t) < MAX_PLAN_ONLY_CHARS and PLAN_ONLY_RE.search(t) and not SECTION_RE.search(t):
        return False, "只有计划或承诺句，没有交付正文"
    if delivery:
        if len(t) < MIN_DELIVERY_CHARS:
            return False, f"交付类任务正文过短（{len(t)} < {MIN_DELIVERY_CHARS} 字）"
        if not SECTION_RE.search(t):
            return False, "交付类任务缺少成稿结构（小节 / 条目 / 分节标题）"
        missing = [k for k in DELIVERY_REQUIRED if k not in t]
        if missing:
            return False, "交付类任务缺少交付三要素：" + " / ".join(missing)
    return True, ""


def continuation_prompt(reason: str, user_text: str | None) -> str:
    """回注给模型的「把话说完」指令。

    刻意写成 user 轮而不是 system 轮：模型对紧邻的 user 指令响应最稳定，
    且不会污染后面轮次的系统身份。
    """
    goal = (user_text or "").strip()[:120]
    return (
        "【继续完成 · 不得结束】\n"
        f"你上一条只给到了中间态，未达标原因：{reason}。\n"
        f"用户本轮的完整需求是：{goal}\n"
        "现在立刻基于上文已经给你的素材/工具结果，**继续把成稿写完**，要求：\n"
        "1. 不要再复述计划、不要再说「我先…再…」「正在整理」，直接从正文接着写；\n"
        "2. 覆盖用户原话里的每一项需求；缺数据的那一项要如实写明，不得用别的来源冒充；\n"
        "3. 末尾交代三点：完成状态（已完成 / 部分完成并说明差什么）、已覆盖的需求、"
        "完成依据（用了哪些数据或工具结果）；\n"
        "4. 禁止用「待续」「稍后补充」「剩余部分自行处理」收尾；\n"
        "5. 若存在客观阻塞：先把其余能做的部分全部写成稿，再精确列出"
        "「未决项 / 原因 / 当前状态 / 下一步可行路径」。阻塞说明本身不是交付。\n"
        "这一轮就是最终交付，系统不会再替你补后半段。"
    )


def exhausted_note(reason: str, retries: int, aggregated: bool) -> str:
    """收口时仍不达标的**诚实**兜底：不伪装成功，也不把半成品说成周报。

    ``retries`` 只用于说明已经尝试过几轮，**不是触发条件**：真机实测存在
    「补齐轮模型又吐 tool_calls ⇒ delivery_pending 被跳过 ⇒ 直接 finalize」的路径，
    此时 retries 可能远小于上限，若只在上限用尽时才标注，中间态照样会被记成 SUCCEEDED。
    """
    attempt = (f"（已连续补齐 {retries} 轮仍未成稿）" if retries else "（本轮未产出成稿正文）")
    lines = [
        "",
        "",
        "---",
        "【本轮未完成 · 如实说明】",
        f"- 完成状态：未完成{attempt}。",
        f"- 未决项：本次交付的正文；原因是{reason}。",
        "- 当前状态：本轮没有产出可直接使用的成稿，上面的文字不得当作结果使用。",
    ]
    if aggregated:
        lines.append("- 已获取的数据：见本条消息下方「数据来源」引用卡，原始素材由系统代拉，无需你重新收集。")
    lines += [
        "- 下一步可行路径：再发一次同样的需求；或把范围写具体"
        "（例如「只汇总本周审批与邮件，按 3 个小节写」），本系统会重新组织素材成文。",
    ]
    return "\n".join(lines)
